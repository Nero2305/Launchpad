export const stages = ['Saved', 'Applied', 'Interview', 'Offer', 'Closed'] as const;
export type Stage = (typeof stages)[number];
export type Application = {
  id: string;
  company: string;
  role: string;
  location: string;
  stage: Stage;
  applied_on: string | null;
  follow_up: string | null;
  interview_on: string | null;
  url: string | null;
  notes: string;
  created_at?: string;
};
export type Input = Omit<Application, 'id' | 'created_at'>;
export type Metrics = {
  total: number;
  submitted: number;
  active: number;
  interviews: number;
  offers: number;
  progress_rate: number;
  follow_ups_due: number;
  stages: Record<Stage, number>;
  weeks: { week: string; count: number }[];
};
export function dateOffset(days = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}
export function formatDate(value: string | null) {
  return value
    ? new Date(value + 'T12:00:00').toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })
    : 'Not set';
}
export function toInput(a: Application): Input {
  const { company, role, location, stage, applied_on, follow_up, interview_on, url, notes } = a;
  return { company, role, location, stage, applied_on, follow_up, interview_on, url, notes };
}
// Demo IDs are browser-local only. Database IDs are generated by PostgreSQL.
export function demoId(): string {
  return (
    'demo-' +
    Array.from(crypto.getRandomValues(new Uint8Array(16)), (b) =>
      b.toString(16).padStart(2, '0'),
    ).join('')
  );
}
