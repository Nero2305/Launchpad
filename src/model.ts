export function filterApplications(rows: Application[], search: string, stage: string) {
  const query = search.toLowerCase().trim();
  return rows.filter(
    (a) =>
      (stage === 'All stages' || a.stage === stage) &&
      `${a.company} ${a.role} ${a.location}`.toLowerCase().includes(query),
  );
}
export function csvExport(rows: Application[]) {
  const columns = [
    'company',
    'role',
    'location',
    'stage',
    'applied_on',
    'follow_up',
    'interview_on',
    'url',
    'notes',
  ] as const;
  const quote = (value: string | null) => {
    let text = value ?? '';
    if (/^[\s]*[=+@-]/.test(text) || /^[\t\r\n]/.test(text)) text = "'" + text;
    return '"' + text.replaceAll('"', '""') + '"';
  };
  return [columns.join(','), ...rows.map((a) => columns.map((c) => quote(a[c])).join(','))].join(
    '\r\n',
  );
}
